              <div class="faq-item faq-active">
                <h3>¿Qué necesito para comenzar a importar o exportar?</h3>
                <div class="faq-content">
                  <p>Debes contar con un número de CUIT, estar inscripto en la AFIP y registrarte en el Registro de Importadores y Exportadores.</p>
                </div>
                <i class="faq-toggle bi bi-chevron-right"></i>
              </div>

              <div class="faq-item">
                <h3>¿Qué documentos necesito para importar/exportar?</h3>
                <div class="faq-content">
                  <p>Los principales son: Factura comercial, lista de empaque, conocimiento de embarque (Bill of Lading / AWB), certificados de origen y sanitarios (según el producto), declaración aduanera (SIM en Argentina)</p>
                </div>
                <i class="faq-toggle bi bi-chevron-right"></i>
              </div>

              <div class="faq-item">
                <h3>¿Qué costos adicionales debo considerar?</h3>
                <div class="faq-content">
                  <p>Derechos de importación/exportación, IVA y otros impuestos, costos de transporte y seguro, honorarios del despachante de aduana, costos bancarios por transferencias internacionales</p>
                </div>
                <i class="faq-toggle bi bi-chevron-right"></i>
              </div>

              <div class="faq-item">
                <h3>¿Puedo importar como persona física o necesito una empresa?</h3>
                <div class="faq-content">
                  <p>Puedes importar como persona física en casos menores (compras personales), pero para importaciones comerciales es recomendable operar con una empresa.</p>
                </div>
                <i class="faq-toggle bi bi-chevron-right"></i>
              </div>

              <div class="faq-item">
                <h3>¿Necesito de un despachante de aduana para mudarme a otro pais?</h3>
                <div class="faq-content">
                  <p>No, no es obligatorio. Sin embargo, si vas a enviar tus pertenencias por carga internacional, un despachante de aduana puede facilitar los trámites y evitar demoras en la aduana del país de destino.</p>
                </div>
                <i class="faq-toggle bi bi-chevron-right"></i>
              </div>

            </div>

